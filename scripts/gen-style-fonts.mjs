// Writes src/remotion/styles/font-modules.ts from library.json: one lazy import per Google font the
// library styles use, with its CSS family name. Fails if a font, a weight or the latin subset is missing.
// Run: node scripts/gen-style-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lib = JSON.parse(readFileSync(path.join(root, 'src/remotion/styles/library.json'), 'utf8'));
const used = new Map();
for (const e of lib) for (const [mod, weights] of e.fonts) used.set(mod, new Set([...(used.get(mod) ?? []), ...weights.split(',')]));

const rows = [];
const problems = [];
for (const [mod, weights] of [...used].sort()) {
  const file = path.join(root, 'node_modules/@remotion/google-fonts/dist/esm', `${mod}.mjs`);
  let info;
  try {
    info = (await import(pathToFileURL(file).href)).getInfo();
  } catch (err) {
    problems.push(`${mod}: no such font module (${err.message.slice(0, 80)})`);
    continue;
  }
  const normal = info.fonts.normal ?? {};
  for (const w of weights) {
    if (!normal[w]) problems.push(`${mod}: weight ${w} missing (has ${Object.keys(normal).join(',')})`);
    else if (!normal[w].latin) problems.push(`${mod} ${w}: no latin subset`);
  }
  rows.push(`  ${mod}: { family: ${JSON.stringify(info.fontFamily)}, load: () => import('@remotion/google-fonts/${mod}') },`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
writeFileSync(
  path.join(root, 'src/remotion/styles/font-modules.ts'),
  `// Generated by scripts/gen-style-fonts.mjs from library.json. Do not edit by hand.\n\nexport const FONT_MODULES: Record<string, { family: string; load: () => Promise<unknown> }> = {\n${rows.join('\n')}\n};\n`,
);
console.log(`${rows.length} font modules`);
